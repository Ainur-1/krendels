"""
Уход плоскостей от сжатия Земли: почему суточной моделью можно пользоваться.

Кейс задаёт круговые орбиты вокруг шарообразной Земли и не просит учитывать её
сжатие. Это разумное упрощение, но у него есть цена, и назвать её числом лучше, чем
сослаться на постановку. Здесь и считается цена.

Земля не шар, а слегка сплюснута, и её экваториальный избыток массы разворачивает
плоскость орбиты вокруг земной оси. Скорость разворота даётся классической формулой
для среднего движения; для круговой орбиты 550 км при наклонении 87° это −0.391°
в сутки.

Два следствия, оба важны для защиты. За горизонт расчёта — одни сутки — плоскость
уходит на 0.4°, тогда как шаг перебора разносов составляет 5°, а вершина найденного
максимума имеет ширину около 10°. Эффект в десять с лишним раз меньше разрешающей
способности нашего же поиска, и пренебречь им законно. А на длинном горизонте важно
другое: все три плоскости имеют одинаковые высоту и наклонение, значит уходят с
одинаковой скоростью. Абсолютная ориентация группировки за год поворачивается на
143°, взаимный разнос плоскостей сохраняется в точности — а рекомендация состоит
именно в разносе.
"""

from __future__ import annotations

import math

from cosmo_net.config import EARTH_RADIUS_KM
from cosmo_net.geometry.orbit import mean_motion_rad_s, orbit_radius_km

J2 = 1.08262668e-3
"""Коэффициент сжатия Земли. Безразмерный, значение общепринятое (модель EGM96)."""

SECONDS_PER_DAY = 86400.0


def nodal_precession_deg_per_day(altitude_km: float, inclination_deg: float) -> float:
    """
    Скорость ухода восходящего узла, градусов в сутки.

    Знак отрицательный для прямых орбит (наклонение меньше 90°) и положительный для
    обратных; на полярной орбите ровно ноль, потому что множитель `cos(i)` обращается
    в ноль и разворачивать плоскость нечему.
    """

    radius = orbit_radius_km(altitude_km)
    rate = (
        -1.5
        * mean_motion_rad_s(altitude_km)
        * J2
        * (EARTH_RADIUS_KM / radius) ** 2
        * math.cos(math.radians(inclination_deg))
    )
    return math.degrees(rate) * SECONDS_PER_DAY


def drift_over_horizon_deg(
    altitude_km: float, inclination_deg: float, horizon_s: float
) -> float:
    """Насколько плоскость уходит за горизонт расчёта. Знак сохраняется."""

    return nodal_precession_deg_per_day(altitude_km, inclination_deg) * (
        horizon_s / SECONDS_PER_DAY
    )
