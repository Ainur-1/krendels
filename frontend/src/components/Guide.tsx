/**
 * Инструкция по работе с сервисом, вызываемая кнопкой в верхней строке.
 *
 * Кейс отдельным пунктом требует документацию, отвечающую на вопрос «как
 * пользоваться платформой». Держать её только в README неправильно: человек, который
 * впервые открыл сервис на защите, читает экран, а не репозиторий. Поэтому
 * инструкция живёт внутри интерфейса и открывается одним нажатием.
 *
 * Кнопка подписана словом, а не знаком вопроса: знак вопроса привычно пропускают
 * взглядом, а слово «Инструкция» видно сразу — в том числе с проектора.
 *
 * Цвета причин и запаса берутся из тех же переменных, что и сама диаграмма. Если
 * палитра изменится, легенда в инструкции изменится вместе с ней, а не разойдётся.
 */

import { useEffect, useRef } from "react";

import { CAUSE_LABEL, CAUSE_COLOUR } from "../lib/format";
import type { OutageCause } from "../types";

const CAUSES: OutageCause[] = [
  "none",
  "no_client_contact",
  "no_gateway_contact",
  "gateway_offline",
  "network_split",
];

export function Guide({ onClose }: { onClose: () => void }) {
  const dialog = useRef<HTMLDivElement>(null);

  // Esc закрывает, фокус уходит внутрь окна. Без этого с клавиатуры отсюда не выйти,
  // а на защите руки чаще на клавиатуре, чем на мыши.
  useEffect(() => {
    dialog.current?.focus();
    const onKey = (event: KeyboardEvent) => {
      if (event.key === "Escape") onClose();
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div
        className="modal guide"
        role="dialog"
        aria-modal="true"
        aria-labelledby="guide-title"
        tabIndex={-1}
        ref={dialog}
        onClick={(event) => event.stopPropagation()}
      >
        <div className="guide-head">
          <h2 id="guide-title">Как пользоваться сервисом</h2>
          <button className="ghost" onClick={onClose} aria-label="Закрыть инструкцию">
            ✕
          </button>
        </div>

        <div className="guide-body">
          <section>
            <h3>Четыре шага до первого ответа</h3>
            <ol>
              <li>
                Слева, в разделе <b>Сценарий</b>, выберите один из выданных сценариев или
                загрузите свой файл кнопкой <b>Загрузить файл</b>.
              </li>
              <li>
                При желании поменяйте проект: очередь развёртывания, разнос и фазирование
                орбитальных плоскостей, периоды недоступности аппаратов.
              </li>
              <li>
                Нажмите <b>Рассчитать</b> в правом верхнем углу.
              </li>
              <li>Смотрите карту, диаграмму под ней и вкладки внизу.</li>
            </ol>
            <p className="note">
              Числа на экране относятся к последнему расчёту. Пока вы правите параметры, они
              не меняются — и это сделано намеренно: показывать результаты для проекта,
              который никто не считал, нельзя.
            </p>
          </section>

          <section>
            <h3>Карта</h3>
            <p>
              Положение аппаратов в выбранный момент. Цвет — орбитальная плоскость, серые
              аппараты не в строю. Тонкие линии — межспутниковые связи, яркая линия —
              маршрут выбранного наземного пункта до шлюза. Пункты подписаны.
            </p>
          </section>

          <section>
            <h3>Диаграмма доступности</h3>
            <p>
              По полосе на каждый терминал, слева направо — сутки. Цвет говорит, была ли
              связь, а если нет — почему:
            </p>
            <ul className="swatches">
              {CAUSES.map((cause) => (
                <li key={cause}>
                  <i className="swatch" style={{ background: CAUSE_COLOUR[cause] }} />
                  {CAUSE_LABEL[cause]}
                </li>
              ))}
            </ul>
            <p>
              Под каждой полосой идёт узкая лента <b>запаса маршрутов</b>: жёлтая означает,
              что маршрут ровно один и отказ любого аппарата на нём рвёт связь; зелёная —
              что маршрутов два и больше.
            </p>
            <p>
              Щелчок по диаграмме переносит время в эту точку и выбирает этот терминал.
              Кнопка ▶ проигрывает сутки, скорость рядом.
            </p>
          </section>

          <section>
            <h3>Четыре вкладки внизу</h3>
            <dl>
              <dt>Показатели</dt>
              <dd>
                Доступность, видимость, число и длительность перерывов, задержка сигнала по
                каждому пункту. Плюс маршрут на текущем шаге и список перерывов.
              </dd>

              <dt>Сравнение</dt>
              <dd>
                Два и более расчёта рядом, с перечнем параметров, которыми они различаются.
                Чтобы вариант сюда попал, сохраните его при расчёте.
              </dd>

              <dt>Анализ</dt>
              <dd>
                Автоподбор разноса плоскостей — найденное применяется к проекту одним
                нажатием. И анализ критичности: во что обошлась бы потеря каждого аппарата.
              </dd>

              <dt>Устойчивость</dt>
              <dd>
                Четыре исследования сверх постановки: что даёт разрешение доставить данные
                с задержкой, сколько случайных отказов проект переносит, из какого
                классического семейства выросла конфигурация и где стоило бы поставить
                вторую точку приземления.
              </dd>
            </dl>
          </section>

          <section>
            <h3>Загрузка своего сценария</h3>
            <p>
              Формат — <code>cosmo-A-1.0</code>, тот же, что у выданных файлов. Если в файле
              ошибки, сервис покажет <b>все</b> сразу и укажет поле у каждой. Исправьте файл
              и загрузите снова.
            </p>
            <p className="note">
              Число плоскостей, аппаратов, наземных пунктов и шлюзов может быть любым — ничто
              в сервисе не рассчитано именно на выданную конфигурацию.
            </p>
          </section>

          <section>
            <h3>Выгрузка результата</h3>
            <p>
              Кнопка <b>Выгрузить результат</b> отдаёт файл формата{" "}
              <code>cosmo-A-result-1.0</code>: по записи на каждую пару «шаг расчёта —
              терминал», с пустым маршрутом там, где его не было.
            </p>
          </section>

          <section>
            <h3>Коротко о частом</h3>
            <dl>
              <dt>Выбор стратегии маршрутизации в шапке что-то меняет?</dt>
              <dd>
                На доступность — нет: маршрут либо существует, либо нет. Меняется задержка и
                длина трассы, их видно в таблице показателей.
              </dd>

              <dt>Почему нельзя добавить наземный пункт?</dt>
              <dd>
                Выданные данные мы не меняем. Что дал бы второй шлюз, посчитано отдельно и
                показано на вкладке «Устойчивость».
              </dd>

              <dt>Расчёт пропал после перезагрузки страницы</dt>
              <dd>
                Так и должно быть: расчёт занимает доли секунды и делается заново. Сохранённые
                варианты при этом никуда не деваются.
              </dd>
            </dl>
          </section>
        </div>

        <div className="guide-foot">
          <button className="primary" onClick={onClose}>
            Понятно
          </button>
          <span className="hint">Закрыть можно клавишей Esc</span>
        </div>
      </div>
    </div>
  );
}
