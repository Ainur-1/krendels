/**
 * Предупреждение о том, что показанные исследования считались до правки проекта.
 *
 * Результаты переживают переключение вкладок — это удобно. Но ровно поэтому они могут
 * пережить и правку ползунков, а тогда числа на экране относятся к конфигурации,
 * которой больше нет. Молчать об этом нельзя: незамеченное устаревшее число хуже,
 * чем его отсутствие.
 */

export function StaleNotice() {
  return (
    <p className="stale">
      Показанное ниже посчитано до последней правки проекта. Чтобы получить числа для
      текущей конфигурации, запустите нужное исследование заново.
    </p>
  );
}
